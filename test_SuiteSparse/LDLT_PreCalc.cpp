// src/preCalc01.cpp
#include <cstdio>
#include <cstdlib>
#include <vector>
#include "amd.h"
#include "ldl.h"

void write_array(FILE* fp, const char* type, const char* name, const int* arr, int size) {
    fprintf(fp, "constexpr %s %s[%d] = {\n    ", type, name, size);
    for (int i = 0; i < size; ++i) {
        fprintf(fp, "%d%s", arr[i], (i + 1 < size) ? ", " : "");
        if ((i + 1) % 10 == 0 && (i + 1) < size) fprintf(fp, "\n    ");
    }
    fprintf(fp, "\n};\n\n");
}

int main(int argc, char** argv) {
    if (argc < 2) {
        fprintf(stderr, "Usage: %s <output_header_path>\n", argv[0]);
        return EXIT_FAILURE;
    }
    const char* out_header = argv[1];

    // 1. 定义原对称矩阵 A (5x5 示例，CSC上三角存储)
    const int n = 5;
    std::vector<int> Ap_upper = {0, 1, 2, 4, 6, 9};
    std::vector<int> Ai_upper = {0, 1, 0, 2, 1, 3, 0, 2, 4};

    // 对应的无对角线全对称图结构 (A + A^T)，供 AMD 排序使用
    std::vector<int> Ap_amd = {0, 2, 3, 5, 6, 8};
    std::vector<int> Ai_amd = {2, 4, 3, 0, 4, 1, 0, 2};

    // 2. 在主机端使用动态内存调用 AMD
    std::vector<int> P(n), Pinv(n);
    double Control[AMD_CONTROL], Info[AMD_INFO];
    amd_defaults(Control);

    if (amd_order(n, Ap_amd.data(), Ai_amd.data(), P.data(), Control, Info) != AMD_OK) {
        fprintf(stderr, "Error: AMD ordering failed!\n");
        return EXIT_FAILURE;
    }

    // 3. 调用 ldl_symbolic 获取静态消去树 Parent 及非零元结构 Lp
    std::vector<int> Lp(n + 1), Parent(n), Lnz(n), Flag(n);
    ldl_symbolic(n, Ap_upper.data(), Ai_upper.data(), Lp.data(),
                 Parent.data(), Lnz.data(), Flag.data(), P.data(), Pinv.data());

    const int lnz_total = Lp[n];

    // 4. 直接生成嵌入式目标板可用的无依赖 C++ 静态头文件
    FILE* fp = fopen(out_header, "w");
    if (!fp) {
        perror("Failed to open output file");
        return EXIT_FAILURE;
    }

    fprintf(fp, "// AUTO-GENERATED BY preCalc01 - DO NOT EDIT MANUALLY\n");
    fprintf(fp, "#pragma once\n\n");
    fprintf(fp, "namespace EmbeddedLDLT {\n\n");
    fprintf(fp, "constexpr int N = %d;\n", n);
    fprintf(fp, "constexpr int A_NNZ = %zu;\n", Ai_upper.size());
    fprintf(fp, "constexpr int L_NNZ = %d;\n\n", lnz_total);

    write_array(fp, "int", "Ap", Ap_upper.data(), n + 1);
    write_array(fp, "int", "Ai", Ai_upper.data(), static_cast<int>(Ai_upper.size()));
    write_array(fp, "int", "P", P.data(), n);
    write_array(fp, "int", "Pinv", Pinv.data(), n);
    write_array(fp, "int", "Parent", Parent.data(), n);
    write_array(fp, "int", "Lp", Lp.data(), n + 1);
    write_array(fp, "int", "Lnz", Lnz.data(), n);

    fprintf(fp, "} // namespace EmbeddedLDLT\n");
    fclose(fp);

    printf("[preCalc01] Successfully generated static symbolic header: %s (L_NNZ = %d)\n", out_header, lnz_total);
    return EXIT_SUCCESS;
}